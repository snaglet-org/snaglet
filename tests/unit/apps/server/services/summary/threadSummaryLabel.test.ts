/**
 * threadSummaryLabel — the one labeled form a stored thread summary takes when
 * it reaches the agent: who wrote it, how much it covers, and that it is lossy.
 */
import { describe, expect, it } from '@jest/globals';
import { labelThreadSummary } from '@server/services/summary/threadSummaryLabel';

describe('labelThreadSummary', () => {
  it('names the source model, the messages covered and the lossy caveat, then the text', () => {
    const text = labelThreadSummary({
      summaryText: 'We chose option A.',
      messagesCovered: 12,
      modelUsed: 'test-provider/test-model',
    });
    expect(text).toBe(
      'Generated by test-provider/test-model; covers 12 messages. It is lossy: check the messages before relying on a decision recorded here.\n\nWe chose option A.'
    );
  });

  it('says "1 message" in the singular and copes with an unknown model', () => {
    const text = labelThreadSummary({ summaryText: 'X', messagesCovered: 1, modelUsed: null });
    expect(text.startsWith('Generated by a utility model; covers 1 message. ')).toBe(true);
  });

  it('returns null when there is no summary', () => {
    expect(labelThreadSummary(null)).toBeNull();
    expect(labelThreadSummary({ summaryText: '', messagesCovered: 0, modelUsed: null })).toBeNull();
  });
});
