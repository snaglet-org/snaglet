const POSTGRES_PORT = 5432;
const SOCKET_FILE = `.s.PGSQL.${POSTGRES_PORT}`;

interface RecordedCommand {
  executable: string;
  args: string[];
  options?: CommandOptions;
}

function successful(stdout = ''): CommandResult {
  return { exitCode: 0, signal: null, stdout, stderr: '' };
}

function failed(exitCode = 3, stderr = ''): CommandResult {
  return { exitCode, signal: null, stdout: '', stderr };
}

function deferred(): { promise: Promise<void>; resolve: () => void } {
  let resolve!: () => void;
  const promise = new Promise<void>((done) => {
    resolve = done;
  });
  return { promise, resolve };
}

async function waitFor(check: () => boolean): Promise<void> {
  for (let attempt = 0; attempt < 100; attempt += 1) {
    if (check()) return;
    await new Promise((resolve) => setTimeout(resolve, 5));
  }
  throw new Error('Timed out waiting for fake PostgreSQL command');
}

function argumentAfter(args: readonly string[], flag: string): string {
  const index = args.indexOf(flag);
  if (index < 0 || !args[index + 1]) throw new Error(`Fake command missing ${flag}`);
  return args[index + 1];
}

function fakeBinDir(rootDir: string): BinDir {
  const binDir = path.join(rootDir, 'bin');
  return {
    rootDir,
    binDir,
    libDir: path.join(rootDir, 'lib'),
    shareDir: path.join(rootDir, 'share'),
    postgres: path.join(binDir, 'postgres'),
    initdb: path.join(binDir, 'initdb'),
    pgCtl: path.join(binDir, 'pg_ctl'),
    pgDump: path.join(binDir, 'pg_dump'),
    pgRestore: path.join(binDir, 'pg_restore'),
    pgConfig: path.join(binDir, 'pg_config'),
    psql: path.join(binDir, 'psql'),
    createdb: path.join(binDir, 'createdb'),
    dropdb: path.join(binDir, 'dropdb'),
  };
}

function postmasterPidContents(params: {
  pid: number;
  dataDir: string;
  socketDir: string;
  port?: number;
  tcp?: boolean;
}): string {
  return [
    String(params.pid),
    params.dataDir,
    String(Math.floor(Date.now() / 1000)),
    String(params.port ?? POSTGRES_PORT),
    params.tcp ? '' : params.socketDir,
    params.tcp ? '127.0.0.1' : '',
    '0 0',
    'ready',
    '',
  ].join('\n');
}

class FakePostgresCommands {
  readonly commands: RecordedCommand[] = [];
  readonly alivePids = new Set<number>();
  initdbGate: Promise<void> | undefined;
  initdbFailure: CommandResult | undefined;
  startFailure: CommandResult | undefined;
  identityMismatch = false;
  private dataDir = '';
  private nextPid = 31_000;
  private databaseExists = false;

  readonly run: CommandRunner = async (executable, args, options) => {
    this.commands.push({ executable, args: [...args], options });
    const command = path.basename(executable);

    if (command === 'initdb') {
      const dataDir = argumentAfter(args, '-D');
      await mkdir(dataDir, { recursive: true });
      await writeFile(path.join(dataDir, 'partial-initdb-output'), 'owned by fake initdb');
      if (this.initdbGate) await this.initdbGate;
      if (this.initdbFailure) return this.initdbFailure;
      await writeFile(path.join(dataDir, 'PG_VERSION'), '17\n');
      await writeFile(path.join(dataDir, 'postgresql.conf'), '# generated by fake initdb\n');
      return successful();
    }

    if (command === 'pg_ctl') {
      const action = args[0];
      const dataDir = argumentAfter(args, '-D');
      this.dataDir = dataDir;
      const pidPath = path.join(dataDir, 'postmaster.pid');

      if (action === 'status') {
        try {
          const pid = Number((await readFile(pidPath, 'utf8')).split(/\r?\n/, 1)[0]);
          return this.alivePids.has(pid) ? successful() : failed();
        } catch {
          return failed();
        }
      }

      if (action === 'start') {
        if (this.startFailure) return this.startFailure;
        const socketDir = options?.env?.PGHOST;
        if (!socketDir) return failed(1, 'PGHOST missing');
        const pid = this.nextPid++;
        this.alivePids.add(pid);
        await writeFile(
          pidPath,
          postmasterPidContents({
            pid,
            dataDir,
            socketDir,
            port: Number(options?.env?.PGPORT),
            tcp: socketDir === '127.0.0.1',
          })
        );
        if (socketDir !== '127.0.0.1') {
          await mkdir(socketDir, { recursive: true });
          await writeFile(path.join(socketDir, SOCKET_FILE), 'fake socket');
        }
        return successful();
      }

      if (action === 'stop') {
        let socketDir = options?.env?.PGHOST;
        try {
          const lines = (await readFile(pidPath, 'utf8')).split(/\r?\n/);
          this.alivePids.delete(Number(lines[0]));
          socketDir = lines[4] || socketDir;
          await unlink(pidPath);
        } catch {
          // The production runtime makes stop idempotent; mirror it here.
        }
        // eslint-disable-next-line no-restricted-syntax -- intentional: fake runtime mirrors the production stop's idempotency; the socket may already be gone
        if (socketDir) await unlink(path.join(socketDir, SOCKET_FILE)).catch(() => {});
        return successful();
      }
    }

    if (command === 'psql') {
      if (args.some((arg) => arg.includes('pg_postmaster_start_time'))) {
        const lines = (await readFile(path.join(this.dataDir, 'postmaster.pid'), 'utf8')).split(
          /\r?\n/
        );
        return successful(
          JSON.stringify({
            dataDir: this.identityMismatch ? path.join(this.dataDir, 'other') : this.dataDir,
            startedAt: Number(lines[2]),
          })
        );
      }
      return successful(this.databaseExists ? '1\n' : '');
    }
    if (command === 'createdb') {
      this.databaseExists = true;
      return successful();
    }

    throw new Error(`Unexpected fake PostgreSQL command: ${command} ${args.join(' ')}`);
  };

  isPidAlive = (pid: number): boolean => pid === process.pid || this.alivePids.has(pid);

  count(command: string, action?: string): number {
    return this.commands.filter(
      (entry) =>
        path.basename(entry.executable) === command && (!action || entry.args[0] === action)
    ).length;
  }
}

describe('PostgresRuntime managed cluster lifecycle', () => {
  let root: string;
  let fake: FakePostgresCommands;
  let binaries: BinDir;
  const socketDirs = new Set<string>();

  beforeEach(async () => {
    root = await mkdtemp(path.join(tmpdir(), 'snaglet-postgres-runtime-unit-'));
    fake = new FakePostgresCommands();
    binaries = fakeBinDir(path.join(root, 'fake-runtime'));
  });

  afterEach(async () => {
    await Promise.all(
      [...socketDirs].map((socketDir) => rm(socketDir, { recursive: true, force: true }))
    );
    socketDirs.clear();
    await rm(root, { recursive: true, force: true });
  });

  function makeRuntime(
    options: {
      platform?: NodeJS.Platform;
      restrictPath?: PostgresRuntimeOptions['restrictPath'];
      snagletHome?: string;
      dataDir?: string;
      warn?: (line: string) => void;
      recoverInterruptedRestore?: PostgresRuntimeOptions['recoverInterruptedRestore'];
      beforeEnsureDatabase?: PostgresRuntimeOptions['beforeEnsureDatabase'];
    } = {}
  ) {
    const runtime = new PostgresRuntime({
      platform: options.platform ?? 'linux',
      snagletHome: options.snagletHome ?? path.join(root, 'home'),
      dataDir: options.dataDir,
      env: {},
      ensureBinaries: async () => binaries,
      runCommand: fake.run,
      restrictPath:
        options.restrictPath ?? (process.platform === 'win32' ? async () => {} : undefined),
      isPidAlive: fake.isPidAlive,
      log: () => {},
      warn: options.warn ?? (() => {}),
      recoverInterruptedRestore: options.recoverInterruptedRestore ?? (async () => {}),
      beforeEnsureDatabase: options.beforeEnsureDatabase,
    });
    socketDirs.add(runtime.socketDir);
    return runtime;
  }

  it('uses authenticated loopback TCP with a persisted per-cluster port on Windows', async () => {
    const first = makeRuntime({ platform: 'win32' });
    const started = await first.start();
    expect(started).toMatchObject({ state: 'running', host: '127.0.0.1', transport: 'tcp' });
    expect(started.port).toBeGreaterThan(1023);
    const connection = await first.connectionInfo();
    expect(connection.host).toBe('127.0.0.1');
    expect(connection.socketDir).not.toBe(connection.host);
    expect(connection.port).toBe(started.port);
    expect(await readFile(path.join(first.dataDir, 'pg_hba.conf'), 'utf8')).toBe(
      'host all snaglet 127.0.0.1/32 scram-sha-256\n'
    );
    const config = await readFile(path.join(first.dataDir, 'postgresql.conf'), 'utf8');
    expect(config).toContain("listen_addresses = '127.0.0.1'");
    expect(config).toContain("unix_socket_directories = ''");
    const second = makeRuntime({ platform: 'win32' });
    expect(await second.adoptIfRunning()).toBe(true);
    expect((await second.connectionInfo()).port).toBe(connection.port);
    expect((await second.status()).pid).toBe(started.pid);
    const probe = fake.commands.find((entry) =>
      entry.args.some((arg) => arg.includes('pg_postmaster_start_time'))
    );
    expect(probe?.options?.env).toMatchObject({
      PGHOST: '127.0.0.1',
      PGPORT: String(connection.port),
      PGPASSWORD: connection.password,
      PGSSLMODE: 'disable',
    });
    await second.stop();
  });

  it('retains its TCP port across restarts and replaces it when another listener owns it', async () => {
    const runtime = makeRuntime({ platform: 'win32' });
    const first = await runtime.start();
    await runtime.stop();
    expect((await runtime.start()).port).toBe(first.port);
    await runtime.stop();
    const unrelated = createServer();
    await new Promise<void>((resolve, reject) => {
      unrelated.once('error', reject);
      unrelated.listen({ host: '127.0.0.1', port: first.port, exclusive: true }, resolve);
    });
    try {
      expect((await runtime.start()).port).not.toBe(first.port);
    } finally {
      await new Promise<void>((resolve) => unrelated.close(() => resolve()));
    }
    await runtime.stop();
  });

  it('refuses TCP adoption and shutdown when the authenticated server identity differs', async () => {
    const runtime = makeRuntime({ platform: 'win32' });
    await runtime.start();
    fake.identityMismatch = true;
    expect((await runtime.status()).state).toBe('conflict');
    await expect(runtime.adoptIfRunning()).rejects.toThrow(/identity could not be verified/);
    await expect(runtime.stop()).rejects.toThrow(/Refusing to stop/);
    expect(fake.count('pg_ctl', 'stop')).toBe(0);
    fake.identityMismatch = false;
    await runtime.stop();
  });

  it('rejects a changed TCP port record before adopting or stopping a live server', async () => {
    const runtime = makeRuntime({ platform: 'win32' });
    const started = await runtime.start();
    const target = path.join(runtime.dataDir, 'snaglet-connection.conf');
    await writeFile(target, `port = ${started.port === 5432 ? 5433 : 5432}\n`);
    expect((await runtime.status()).state).toBe('conflict');
    await expect(runtime.stop()).rejects.toThrow(/Refusing to stop/);
    await writeFile(target, `port = ${started.port}\n`);
    await runtime.stop();
  });

  it('reclaims abandoned Windows lease metadata even when its old PID is still alive', async () => {
    if (process.platform !== 'win32') return;
    const runtime = makeRuntime();
    await runtime.ensureCluster();
    const lockPath = `${runtime.dataDir}.snaglet-runtime-lock`;
    await writeFile(
      lockPath,
      JSON.stringify({ pid: process.pid, token: 'abandoned-token', lease: 'windows-pipe-v1' })
    );
    await runtime.ensureCluster();
    expect(
      (await readdir(path.dirname(lockPath))).some((name) =>
        name.includes('.snaglet-runtime-lock.stale-')
      )
    ).toBe(true);
    expect(fake.count('initdb')).toBe(1);
  });

  it('sets credential privacy while the newly created file is still empty', async () => {
    const contentsAtRestriction: string[] = [];
    const runtime = makeRuntime({
      restrictPath: async (target, directory) => {
        if (!directory) contentsAtRestriction.push(await readFile(target, 'utf8'));
      },
    });
    await runtime.ensureCluster();
    expect(contentsAtRestriction[0]).toBe('');
    expect((await readFile(runtime.passwordPath, 'utf8')).trim()).toHaveLength(43);
  });

  it('never writes credential bytes when the private ACL cannot be established', async () => {
    const runtime = makeRuntime({
      restrictPath: async () => {
        throw new Error('simulated ACL refusal');
      },
    });
    await expect(runtime.ensureCluster()).rejects.toThrow(/simulated ACL refusal/);
    expect(await readFile(runtime.passwordPath, 'utf8')).toBe('');
    expect(fake.count('initdb')).toBe(0);
  });

  it('initializes exactly once and preserves a stable 0600 password', async () => {
    const runtime = makeRuntime();

    await runtime.ensureCluster();
    const firstPassword = (await readFile(runtime.passwordPath, 'utf8')).trim();
    expect(firstPassword).toHaveLength(43); // 32 random bytes encoded as base64url.
    if (process.platform !== 'win32')
      expect((await stat(runtime.passwordPath)).mode & 0o777).toBe(0o600);
    expect(fake.count('initdb')).toBe(1);

    // Existing credentials are retained and their permissions are repaired.
    await chmod(runtime.passwordPath, 0o644);
    await runtime.ensureCluster();

    expect((await readFile(runtime.passwordPath, 'utf8')).trim()).toBe(firstPassword);
    if (process.platform !== 'win32')
      expect((await stat(runtime.passwordPath)).mode & 0o777).toBe(0o600);
    expect(fake.count('initdb')).toBe(1);
  });

  it('serializes concurrent initialization from two runtime instances', async () => {
    const first = makeRuntime();
    const second = makeRuntime({ snagletHome: first.snagletHome, dataDir: first.dataDir });
    const gate = deferred();
    fake.initdbGate = gate.promise;

    const initializing = Promise.all([first.ensureCluster(), second.ensureCluster()]);
    await waitFor(() => fake.count('initdb') >= 1);
    gate.resolve();
    await initializing;

    expect(fake.count('initdb')).toBe(1);
    expect(await readFile(path.join(first.dataDir, 'PG_VERSION'), 'utf8')).toBe('17\n');
  });

  it('cleans an owned staging directory after disk-full without promoting or touching siblings', async () => {
    const runtime = makeRuntime();
    await mkdir(runtime.snagletHome, { recursive: true });
    const sentinel = path.join(runtime.snagletHome, 'keep-outside-staging.txt');
    await writeFile(sentinel, 'preserve me');
    fake.initdbFailure = failed(1, 'No space left on device');

    await expect(runtime.ensureCluster()).rejects.toThrow(
      /no cluster was promoted[\s\S]*No space left/i
    );

    await expect(stat(runtime.dataDir)).rejects.toMatchObject({ code: 'ENOENT' });
    expect(await readFile(sentinel, 'utf8')).toBe('preserve me');
    expect(
      (await readdir(runtime.snagletHome)).filter((entry) => entry.startsWith('.postgres.init-'))
    ).toEqual([]);
    expect(fake.count('initdb')).toBe(1);
  });

  it('refuses to rotate a missing password for an initialized cluster', async () => {
    const runtime = makeRuntime();
    await runtime.ensureCluster();
    await unlink(runtime.passwordPath);

    await expect(runtime.ensureCluster()).rejects.toThrow(/missing .*pg-password.*refusing/i);
    expect(fake.count('initdb')).toBe(1);
  });

  it('writes the D10 configuration and never places the password itself in argv', async () => {
    const runtime = makeRuntime();
    await runtime.ensureCluster();
    await runtime.start();

    const password = (await readFile(runtime.passwordPath, 'utf8')).trim();
    const config = await readFile(path.join(runtime.dataDir, 'postgresql.conf'), 'utf8');
    expect(config).toContain('shared_buffers = 128MB');
    expect(config).toContain('max_wal_size = 256MB');
    expect(config).toContain('min_wal_size = 80MB');
    expect(config).toContain('max_connections = 30');
    expect(config).toContain(`unix_socket_directories = '${runtime.socketDir}'`);
    expect(config).toContain("listen_addresses = ''");
    expect(config).toContain('logging_collector = on');

    const initdb = fake.commands.find((entry) => path.basename(entry.executable) === 'initdb');
    expect(initdb?.args).toEqual(
      expect.arrayContaining([
        '--data-checksums',
        '--encoding=UTF8',
        '--locale=C',
        '--username=snaglet',
        '--auth=scram-sha-256',
        `--pwfile=${runtime.passwordPath}`,
      ])
    );
    for (const command of fake.commands) {
      expect(command.args.join(' ')).not.toContain(password);
    }
    expect(initdb?.options?.env?.PGPASSWORD).toBeUndefined();
    expect(fake.count('createdb')).toBe(1);
  });

  it('runs beforeEnsureDatabase after restore recovery and before database creation on a fresh cluster', async () => {
    const lifecycle: string[] = [];
    let callbackContext:
      | Parameters<NonNullable<PostgresRuntimeOptions['beforeEnsureDatabase']>>[0]
      | null = null;
    const runtime = makeRuntime({
      recoverInterruptedRestore: async () => {
        lifecycle.push('restore-recovery');
        expect(fake.count('psql')).toBe(0);
        expect(fake.count('createdb')).toBe(0);
      },
      beforeEnsureDatabase: async (context) => {
        lifecycle.push('before-ensure-database');
        callbackContext = context;
        expect(lifecycle).toEqual(['restore-recovery', 'before-ensure-database']);
        expect(fake.count('psql')).toBe(0);
        expect(fake.count('createdb')).toBe(0);
      },
    });

    await runtime.start();

    expect(callbackContext).toMatchObject({
      clusterWasInitialized: false,
      connection: {
        socketDir: runtime.socketDir,
        database: 'snaglet',
        user: 'snaglet',
      },
    });
    expect(lifecycle).toEqual(['restore-recovery', 'before-ensure-database']);
    expect(fake.count('psql')).toBe(1);
    expect(fake.count('createdb')).toBe(1);
  });

  it('reports an existing cluster to beforeEnsureDatabase', async () => {
    let clusterWasInitialized: boolean | undefined;
    const runtime = makeRuntime({
      beforeEnsureDatabase: async (context) => {
        clusterWasInitialized = context.clusterWasInitialized;
      },
    });
    await runtime.ensureCluster();

    await runtime.start();

    expect(clusterWasInitialized).toBe(true);
    expect(fake.count('initdb')).toBe(1);
    expect(fake.count('createdb')).toBe(1);
  });

  it('does not inspect or create the database when beforeEnsureDatabase fails', async () => {
    const runtime = makeRuntime({
      beforeEnsureDatabase: async () => {
        throw new Error('migration gate rejected target creation');
      },
    });

    await expect(runtime.start()).rejects.toThrow('migration gate rejected target creation');

    expect(fake.count('psql')).toBe(0);
    expect(fake.count('createdb')).toBe(0);
  });

  it('derives distinct short socket paths for different Snaglet homes', () => {
    const first = makeRuntime({ snagletHome: path.join(root, 'lane-one') });
    const second = makeRuntime({ snagletHome: path.join(root, 'lane-two') });

    expect(first.socketDir).not.toBe(second.socketDir);
    expect(path.basename(first.socketDir)).toMatch(/^snaglet-pg-[a-f0-9]{12}$/);
    expect(Buffer.byteLength(path.join(first.socketDir, SOCKET_FILE))).toBeLessThan(104);
    expect(Buffer.byteLength(path.join(second.socketDir, SOCKET_FILE))).toBeLessThan(104);
  });

  it('adopts a compatible running postmaster without starting a second one', async () => {
    const first = makeRuntime();
    await first.start();
    expect(fake.count('pg_ctl', 'start')).toBe(1);

    const second = makeRuntime({ snagletHome: first.snagletHome, dataDir: first.dataDir });
    await expect(second.adoptIfRunning()).resolves.toBe(true);
    expect(fake.count('pg_ctl', 'start')).toBe(1);

    const status = await second.status();
    expect(status).toMatchObject({ state: 'running', running: true, socketReady: true });
  });

  it('parks a dead postmaster pid file before allowing a later start', async () => {
    const runtime = makeRuntime();
    await runtime.ensureCluster();
    const pidPath = path.join(runtime.dataDir, 'postmaster.pid');
    await writeFile(
      pidPath,
      postmasterPidContents({ pid: 41_000, dataDir: runtime.dataDir, socketDir: runtime.socketDir })
    );

    await expect(runtime.adoptIfRunning()).resolves.toBe(false);
    await expect(readFile(pidPath, 'utf8')).rejects.toMatchObject({ code: 'ENOENT' });
    expect(
      (await readdir(runtime.dataDir)).some((entry) => entry.startsWith('postmaster.pid.stale-'))
    ).toBe(true);
    expect(fake.count('pg_ctl', 'status')).toBe(0);
  });

  it('refuses a live mismatched postmaster without deleting or parking its pid file', async () => {
    const runtime = makeRuntime();
    await runtime.ensureCluster();
    const pidPath = path.join(runtime.dataDir, 'postmaster.pid');
    const conflict = postmasterPidContents({
      pid: 42_000,
      dataDir: path.join(root, 'different-cluster'),
      socketDir: path.join(root, 'different-socket'),
    });
    fake.alivePids.add(42_000);
    await writeFile(pidPath, conflict);

    await expect(runtime.adoptIfRunning()).rejects.toThrow(/conflicts.*refusing to unlink/i);
    expect(await readFile(pidPath, 'utf8')).toBe(conflict);
    expect(
      (await readdir(runtime.dataDir)).some((entry) => entry.startsWith('postmaster.pid.stale-'))
    ).toBe(false);
  });

  it('starts every postmaster with room for 256 locks per transaction, an existing cluster too', async () => {
    const first = makeRuntime();
    await first.start();
    await first.stop('fast');
    // Initialized without the option in its config, like clusters created before it.
    const config = await readFile(path.join(first.dataDir, 'postgresql.conf'), 'utf8');
    expect(config).not.toContain('max_locks_per_transaction');

    const restarted = makeRuntime({ snagletHome: first.snagletHome, dataDir: first.dataDir });
    await restarted.start();

    const starts = fake.commands.filter(
      (entry) => path.basename(entry.executable) === 'pg_ctl' && entry.args[0] === 'start'
    );
    expect(starts).toHaveLength(2);
    for (const start of starts)
      expect(argumentAfter(start.args, '-o')).toBe('-c max_locks_per_transaction=256');
  });

  it('fast-stops and restarts a live postmaster whose socket directory vanished', async () => {
    const warn = jest.fn<(line: string) => void>();
    const runtime = makeRuntime({ warn });
    await runtime.start();
    await rm(runtime.socketDir, { recursive: true, force: true });

    await runtime.start();

    expect(fake.count('pg_ctl', 'start')).toBe(2);
    const stop = fake.commands.find(
      (entry) => path.basename(entry.executable) === 'pg_ctl' && entry.args[0] === 'stop'
    );
    expect(stop?.args).toEqual(['stop', '-D', runtime.dataDir, '-m', 'fast', '-w']);
    expect(warn).toHaveBeenCalledWith(expect.stringMatching(/lost its socket directory/i));
    expect(await runtime.status()).toMatchObject({ state: 'running', socketReady: true });
  });

  it('reports only the latest PostgreSQL log file last 40 lines when pg_ctl start fails', async () => {
    const runtime = makeRuntime();
    await runtime.ensureCluster();
    const logDir = path.join(runtime.dataDir, 'log');
    const olderLog = path.join(logDir, 'postgresql-older.log');
    const latestLog = path.join(logDir, 'postgresql-latest.log');
    const lines = Array.from({ length: 41 }, (_, index) => `line ${index + 1}`);
    await writeFile(olderLog, 'old log must not be selected');
    await writeFile(latestLog, lines.join('\n'));
    await utimes(olderLog, new Date(1_000_000), new Date(1_000_000));
    await utimes(latestLog, new Date(2_000_000), new Date(2_000_000));
    fake.startFailure = failed(1, 'simulated pg_ctl start failure');

    let thrown: unknown;
    try {
      await runtime.start();
    } catch (error: unknown) {
      thrown = error;
    }

    expect(thrown).toBeInstanceOf(Error);
    const message = (thrown as Error).message;
    expect(message).toContain('simulated pg_ctl start failure');
    expect(message).not.toContain('old log must not be selected');
    const tail = message.split('Last PostgreSQL log lines:\n')[1];
    expect(tail?.split('\n')).toEqual(lines.slice(1));
  });

  it('maps fast and smart shutdown modes to pg_ctl and remains restartable', async () => {
    const runtime = makeRuntime();
    await runtime.start();
    await runtime.stop('fast');
    await runtime.start();
    await runtime.stop('smart');

    const stops = fake.commands.filter(
      (entry) => path.basename(entry.executable) === 'pg_ctl' && entry.args[0] === 'stop'
    );
    expect(stops.map((entry) => entry.args)).toEqual([
      ['stop', '-D', runtime.dataDir, '-m', 'fast', '-w'],
      ['stop', '-D', runtime.dataDir, '-m', 'smart', '-w'],
    ]);
    await expect(runtime.stop('fast')).resolves.toBeUndefined();
    expect(fake.count('pg_ctl', 'stop')).toBe(2);
  });

  it('refuses an unknown non-empty target without changing its contents', async () => {
    const dataDir = path.join(root, 'unknown-data');
    const sentinel = path.join(dataDir, 'legacy-data.bin');
    await mkdir(dataDir, { recursive: true });
    await writeFile(sentinel, 'preserve me');
    const runtime = makeRuntime({ dataDir });

    await expect(runtime.ensureCluster()).rejects.toThrow(/refusing.*non-empty directory/i);
    expect(await readFile(sentinel, 'utf8')).toBe('preserve me');
    expect(fake.count('initdb')).toBe(0);
  });

  it('warns for cloud-synced locations and rejects newer runtime metadata', async () => {
    const warn = jest.fn<(line: string) => void>();
    await guardPostgresDataDir(path.join(root, 'iCloud', 'postgres'), warn);
    expect(warn).toHaveBeenCalledWith(expect.stringMatching(/cloud-synced.*iCloud/i));

    const dataDir = path.join(root, 'meta-cluster');
    await mkdir(dataDir, { recursive: true });
    await writeFile(
      path.join(dataDir, 'snaglet-meta.json'),
      JSON.stringify({
        pgMajor: 18,
        pgvectorVersion: '0.8.5',
        migrationCount: 0,
        lastOpenedAt: new Date().toISOString(),
      })
    );
    await expect(guardPostgresDataDir(dataDir, warn)).rejects.toThrow(/newer.*PostgreSQL 18/i);
  });

  it('compares migration counts only within the same numbering epoch', async () => {
    const warn = jest.fn<(line: string) => void>();
    const writeMeta = async (dir: string, meta: object) => {
      await mkdir(dir, { recursive: true });
      await writeFile(path.join(dir, 'snaglet-meta.json'), JSON.stringify(meta));
    };

    // Older-epoch stamps (no epoch field, or an earlier epoch) counted a
    // different numbering, so a count above this build's is NOT a downgrade.
    const unversionedDir = path.join(root, 'unversioned-epoch-cluster');
    await writeMeta(unversionedDir, {
      pgMajor: 17,
      pgvectorVersion: '0.8.5',
      migrationCount: 79,
      lastOpenedAt: new Date().toISOString(),
    });
    await expect(guardPostgresDataDir(unversionedDir, warn)).resolves.toBeUndefined();

    const olderDir = path.join(root, 'older-epoch-cluster');
    await writeMeta(olderDir, {
      pgMajor: 17,
      pgvectorVersion: '0.8.5',
      migrationEpoch: MIGRATION_EPOCH - 1,
      migrationCount: 78,
      lastOpenedAt: new Date().toISOString(),
    });
    await expect(guardPostgresDataDir(olderDir, warn)).resolves.toBeUndefined();

    // Same epoch, more migrations than this build bundles -> refuse.
    const aheadDir = path.join(root, 'ahead-epoch-cluster');
    await writeMeta(aheadDir, {
      pgMajor: 17,
      pgvectorVersion: '0.8.5',
      migrationEpoch: MIGRATION_EPOCH,
      migrationCount: 9_999,
      lastOpenedAt: new Date().toISOString(),
    });
    await expect(guardPostgresDataDir(aheadDir, warn)).rejects.toThrow(/Refusing downgrade/i);

    // A future epoch -> refuse regardless of count.
    const futureDir = path.join(root, 'future-epoch-cluster');
    await writeMeta(futureDir, {
      pgMajor: 17,
      pgvectorVersion: '0.8.5',
      migrationEpoch: MIGRATION_EPOCH + 1,
      migrationCount: 1,
      lastOpenedAt: new Date().toISOString(),
    });
    await expect(guardPostgresDataDir(futureDir, warn)).rejects.toThrow(
      new RegExp(`migration epoch ${MIGRATION_EPOCH + 1}`, 'i')
    );
  });
});

describe('PostgresRuntime — SNAGLET_PG_DATA_DIR path resolution', () => {
  // `.env` values are never shell-expanded, so SNAGLET_PG_DATA_DIR=~/… would
  // resolve against the process cwd and initialize a stray cluster under
  // `<repo>/~/…`. The env value expands `~` and rejects relatives.
  let root: string;
  const socketDirs = new Set<string>();

  beforeEach(async () => {
    root = await mkdtemp(path.join(tmpdir(), 'snaglet-postgres-runtime-env-'));
  });

  afterEach(async () => {
    await Promise.all(
      [...socketDirs].map((socketDir) => rm(socketDir, { recursive: true, force: true }))
    );
    socketDirs.clear();
    await rm(root, { recursive: true, force: true });
  });

  function makeRuntimeWithEnv(env: NodeJS.ProcessEnv): PostgresRuntime {
    const runtime = new PostgresRuntime({
      platform: 'linux',
      snagletHome: path.join(root, 'home'),
      env,
      ensureBinaries: async () => fakeBinDir(path.join(root, 'fake-runtime')),
      runCommand: async () => successful(),
      isPidAlive: () => false,
      log: () => {},
      warn: () => {},
    });
    socketDirs.add(runtime.socketDir);
    return runtime;
  }

  it('expands SNAGLET_PG_DATA_DIR=~/… against the user home directory', () => {
    const runtime = makeRuntimeWithEnv({ SNAGLET_PG_DATA_DIR: '~/snaglet-test-pg-tilde' });
    expect(runtime.dataDir).toBe(path.join(homedir(), 'snaglet-test-pg-tilde'));
  });

  it('leaves an absolute SNAGLET_PG_DATA_DIR unchanged', () => {
    const dataDir = path.join(root, 'explicit-pg-data');
    const runtime = makeRuntimeWithEnv({ SNAGLET_PG_DATA_DIR: dataDir });
    expect(runtime.dataDir).toBe(dataDir);
  });

  it('rejects a bare relative SNAGLET_PG_DATA_DIR instead of resolving against cwd', () => {
    expect(() => makeRuntimeWithEnv({ SNAGLET_PG_DATA_DIR: 'relative/pg-data' })).toThrow(
      /SNAGLET_PG_DATA_DIR must be an absolute path/
    );
  });

  it('falls back to <snagletHome>/postgres when SNAGLET_PG_DATA_DIR is unset', () => {
    const runtime = makeRuntimeWithEnv({});
    expect(runtime.dataDir).toBe(path.join(root, 'home', 'postgres'));
  });
});
