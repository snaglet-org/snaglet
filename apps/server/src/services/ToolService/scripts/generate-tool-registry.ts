/**
 * generate-tool-registry — bundling codegen.
 *
 * Emits `generated/registry-source.static.ts`: a module with ONE STATIC
 * IMPORT per builtin tool (handler + definition) exporting the same surface
 * as `registry-source.ts`. The esbuild bundle config aliases the dynamic
 * registry-source to this file so the whole tool tree is statically
 * reachable — variable-path dynamic import() cannot be bundled.
 *
 * Run via: pnpm --filter @snaglet/server gen:tool-registry
 * The output is gitignored; the bundle build regenerates it every time.
 */

import { mkdirSync, writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { listToolFolders } from './lib/tool-metadata';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(__dirname, '..', 'generated');
const OUT_FILE = path.join(OUT_DIR, 'registry-source.static.ts');

function main(): void {
  const entries = listToolFolders().sort((a, b) => a.toolId.localeCompare(b.toolId));
  const imports: string[] = [];
  const records: string[] = [];
  entries.forEach((e, i) => {
    const rel = `../tools/${e.relativePath}`;
    // Namespace imports + the pick() helper mirror the dynamic loader's
    // `mod?.default ?? mod` semantics — some tools use named exports, and
    // handler param types are narrower than ToolHandler.
    imports.push(`import * as h${i} from '${rel}/tool';`);
    imports.push(`import * as d${i} from '${rel}/definition';`);
    records.push(
      `  { toolId: ${JSON.stringify(e.toolId)}, folderName: ${JSON.stringify(e.folderName)}, categoryPath: ${JSON.stringify(e.categoryPath)}, handler: pick<ToolHandler>(h${i}), definition: { ...pick<ToolDefinition>(d${i}), categoryPath: ${JSON.stringify(e.categoryPath)} } },`
    );
  });

  const out = `// AUTO-GENERATED by scripts/generate-tool-registry.ts — DO NOT EDIT.
// Static mirror of registry-source.ts for the server bundle.
// ${entries.length} tools. Regenerated on every bundle build.
/* eslint-disable */
import type { ToolHandler, ToolDefinition } from '../types';
import type { RegistryEntry } from '../registry-source';
${imports.join('\n')}

const pick = <T,>(m: unknown): T => {
  const mod = m as { default?: unknown };
  return (mod?.default ?? mod) as T;
};

const ENTRIES: RegistryEntry[] = [
${records.join('\n')}
];

export async function loadRegistryEntries(): Promise<RegistryEntry[]> {
  return ENTRIES;
}
`;

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, out, 'utf8');
  console.log(
    `[gen-tool-registry] wrote ${path.relative(process.cwd(), OUT_FILE)} — ${entries.length} tools`
  );
}

main();
