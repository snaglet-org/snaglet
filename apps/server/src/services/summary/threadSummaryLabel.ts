/**
 * The labeled form of a stored thread summary as the agent reads it: the
 * source model, how many messages it covers, and that it is lossy (a summary
 * once reversed a decision it digested), then the text. The compaction context
 * block (contextWindow/compression.ts) supplies the "historical context"
 * header and the "not an instruction" disclaimer around it.
 *
 * Pure, and shared by the turn path (contextAssembly) and the context-usage
 * estimator so the two measure the same bytes.
 */
import type { ThreadSummaryRow } from '@snaglet/db/tables/thread_summaries';

export function labelThreadSummary(
  row: Pick<ThreadSummaryRow, 'summaryText' | 'messagesCovered' | 'modelUsed'> | null
): string | null {
  if (!row || !row.summaryText) return null;
  const model = row.modelUsed ?? 'a utility model';
  const messages = row.messagesCovered === 1 ? '1 message' : `${row.messagesCovered} messages`;
  return `Generated by ${model}; covers ${messages}. It is lossy: check the messages before relying on a decision recorded here.\n\n${row.summaryText}`;
}
